// DocHeader is the first line of docs/benchmark.md.
const DocHeader = "<!-- Generated by go run -tags testbed ./testbed/bench. Don't edit by hand: rerun the benchmark. -->"

// Framing is the honest framing paragraph of PRD 22.3, word for word. Its
// "anonymous" is the one exception the wording test allows.
const Framing = "We wrote both Roadie and the testbed, so read this as a regression suite with a scoreboard, not an independent review. " +
	"Every scenario is something we built Roadie to handle. The canaries are checked by a separate oracle that does not use Roadie's code. " +
	"Pseudonymised data is still personal data under the GDPR: these numbers show what Roadie removed from these fixtures, not that a copy of your site is anonymous."

// NotShown is "What this does not show" (qa.md 8.3 item 6).
var NotShown = []string{
	"Names and addresses in free text that verify cannot spot without the known-value list (`verify --from` the production dump).",
	"Encrypted columns: Roadie reports them (`data.encrypted`) but can't read or rewrite them.",
	"Files Roadie does not rewrite: PDF invoices, uploads and images with EXIF GPS. verify lists the ones it finds.",
	"Object caches and search indexes outside the database (Redis, Elasticsearch): flush them after a copy.",
	"Third-party copies of the data: Mailchimp lists, Stripe customers and the like stay where they are.",
}

// Headline is the scoreboard's one sentence (PRD 22.3).
func Headline(s Summary) string {
	return fmt.Sprintf("Roadie left %s of %s seeded personal values and %s of %s live keys; verify caught %d of %d unsafe stagings with %s false alarms in %s checks of clean ones.",
		num(s.CanarySurvivors), num(s.Canaries), num(s.LiveKeysSurvived), num(s.LiveKeys), s.VerifyRecall, s.VerifyBad, num(s.FalseAlarms), num(s.ControlChecks))
}

// WriteDoc writes docs/benchmark.md from a results.json and the manifest
// (titles, kinds, stacks). It prints canary IDs and counts only: results.json
// holds no value; every gate detail was written from IDs and masked keys.
func WriteDoc(w io.Writer, r Results, f *manifest.File) error {
	b := &docWriter{}
	byID := map[string]manifest.Scenario{}
	kinds := map[string]int{}
	for _, s := range f.Scenarios {
		byID[s.ID] = s
	}
	for _, s := range r.Scored.Scenarios {
		kinds[byID[s.ID].Kind]++
	}
	sum := r.Scored.Summary

	b.line(DocHeader)
	b.line("")
	b.line("# Roadie benchmark")
	b.line("")
	b.linef("The testbed (`testbed/`) is a sealed Docker network: a production WooCommerce shop and its staging copy, a Laravel app, PostgreSQL, an SSH host with a copy of production, "+
		"a sinkhole that answers for the whole internet, stand-ins for the payment and messaging APIs, Mailpit and Echo. This run had %d scenarios (%s). "+
		"For each one the benchmark seeds the input with canaries (unique fake personal values and keys), runs `rhythm-roadie` as `testbed/scenarios.yaml` says "+
		"and judges the result with four gates: (1) a separate oracle finds no canary in the output in any encoding, (2) every serialized value still unserializes in real PHP and row counts match, "+
		"(3) nothing reaches the sinkhole, a stub with a live key or a real recipient during the run and a side-effect drill after it, (4) Roadie's own verify passes. "+
		"The copy must also boot. A control pass verifies the clean inputs %d times each and counts every finding at or above low as a false alarm. Other tools run on the same inputs where they can.",
		sum.Scenarios, kindList(kinds), r.Scored.Control.Rounds)
	b.line("")
	b.line(Framing)
	b.line("")
	b.line("**" + Headline(sum) + "**")
	b.line("")
	b.linef("%d scenarios: %d caught, %d missed, %d error, %d pending.", sum.Scenarios, sum.Outcomes[Caught], sum.Outcomes[Missed], sum.Outcomes[Errored], sum.Outcomes[Pending])
	b.line("")

	m := r.Run.Meta
	b.line("## Run")
	b.line("")
	b.line("| | |")
	b.line("|---|---|")
	b.row("Date", orDash(m.Date))
	b.row("Roadie", orDash(m.RoadieVersion))
	b.row("OS and arch", m.OS+"/"+m.Arch)
	b.row("CPU", fmt.Sprintf("%s, %d cores", orDash(m.CPU), m.Cores))
	b.row("RAM", fmt.Sprintf("%s MB", num(int(m.RAMMB))))
	b.row("Disk", orDash(m.Disk))
	b.row("Docker", orDash(m.Docker))
	b.row("Go", orDash(m.GoVersion))
	b.row("Wall time", dur(m.WallMS))
	b.line("")

	b.line("## Scenarios")
	b.line("")
	b.line("| # | Kind | Stack | Scenario | Roadie | Gates |")
	b.line("|---|---|---|---|---|---|")
	for _, s := range r.Scored.Scenarios {
		ms := byID[s.ID]
		out := s.Outcome
		if out == Caught {
			out = "**caught**"
		}
		b.row(s.ID, ms.Kind, ms.Stack, cmpOr(s.Title, ms.Title), out, gateSummary(s))
	}
	b.line("")
	b.line("**caught**: every gate held · missed: a gate failed (see Details) · error: the harness couldn't run it · pending: a part Roadie or the testbed doesn't have yet (the reason is in Details)")
	b.line("")

	b.line("## Canary survival")
	b.line("")
	b.linef("The oracle looked for %s seeded personal values and %s live keys in every output, in each encoding below (and each in its mysqldump-escaped spelling).",
		num(sum.Canaries), num(sum.LiveKeys))
	b.line("")
	b.line("| Encoding | Found |")
	b.line("|---|---|")
	encs := oracle.Encodings()
	for e := range sum.ByEncoding {
		if !slices.Contains(encs, e) {
			encs = append(encs, e)
		}
	}
	for _, e := range encs {
		b.row(e, num(sum.ByEncoding[e]))
	}
	b.line("")
	b.line("| Gate | Result | Target |")
	b.line("|---|---|---|")
	b.row("Personal values left", fmt.Sprintf("%s of %s", num(sum.CanarySurvivors), num(sum.Canaries)), "0")
	b.row("Live keys left", fmt.Sprintf("%s of %s", num(sum.LiveKeysSurvived), num(sum.LiveKeys)), "0")
	b.row("Test keys changed", num(sum.TestKeysChanged), "0")
	b.row("Serialized values that no longer unserialize", fmt.Sprintf("%s of %s checked", num(sum.IntegrityFailures), num(sum.IntegrityChecked)), "0")
	b.row("Scenarios whose row counts changed", num(sum.RowsDiffer), "0")
	b.row("Boot failures", num(sum.BootFailures), "0")
	b.line("")

	b.line("## Side effects")
	b.line("")
	b.line("Counted during each prepare and copy that has gate 3 (with the traffic generator and the host cron where the scenario says so) and the side-effect drill after it: cron, Action Scheduler, an order, a password reset, a subscription renewal and every webhook, in rounds.")
	b.line("")
	b.line("| | Result | Target |")
	b.line("|---|---|---|")
	b.row("Connections that reached the sinkhole", num(sum.Sinkhole), "0")
	b.row("Stub calls with a live key", num(sum.StubLive), "0")
	b.row("Echo captures to recipients outside the reserved domains", num(sum.EchoReal), "0")
	b.line("")
	if rows := gate3Rows(r); len(rows) > 0 {
		b.line("| # | Sinkhole | Live stub calls | Real recipients | Drill rounds | Requests |")
		b.line("|---|---|---|---|---|---|")
		for _, row := range rows {
			b.row(row...)
		}
		b.line("")
	}

	b.line("## verify")
	b.line("")
	c := r.Scored.Control
	b.linef("Recall: %d of %d unsafe stagings caught with the expected finding IDs and exit code. False alarms: %s in %s checks of clean inputs (%d rounds each; any finding at or above low counts).",
		sum.VerifyRecall, sum.VerifyBad, num(c.FalseAlarms), num(c.Checks), c.Rounds)
	b.line("")
	b.line("| # | Unsafe staging | verify | Found |")
	b.line("|---|---|---|---|")
	for _, s := range r.Scored.Scenarios {
		ms := byID[s.ID]
		if ms.Kind != manifest.KindVerify || ms.Good {
			continue
		}
		var ids []string
		for _, cs := range s.Cases {
			ids = append(ids, cs.IDs...)
		}
		slices.Sort(ids)
		b.row(s.ID, cmpOr(s.Title, ms.Title), s.Outcome, orDash(strings.Join(slices.Compact(ids), ", ")))
	}
	b.line("")
	if len(c.ByInput) > 0 {
		b.line("| Clean input | False alarms |")
		b.line("|---|---|")
		ins := make([]string, 0, len(c.ByInput))
		for k := range c.ByInput {
			ins = append(ins, k)
		}
		slices.Sort(ins)
		for _, k := range ins {
			b.row(k, num(c.ByInput[k]))
		}
		b.line("")
	}
	if len(c.IDs) > 0 {
		b.line("False alarm finding IDs: " + strings.Join(c.IDs, ", ") + ".")
		b.line("")
	}
	for _, s := range c.Skipped {
		b.line("- Not verified: " + s)
	}
	if len(c.Skipped) > 0 {
		b.line("")
	}

	b.line("## Performance")
	b.line("")
	b.line("r17: a generated WordPress dump (gzip) with a 50 MB serialized row, hex blobs, a trigger and canaries first, last and around 4 GiB, copied dump file to dump file. " +
		"Targets (PRD 22.3, on 8 cores and NVMe): transform at least 100 MB/s, index at least 300 MB/s, a 5 GB dump with verify in under 3 minutes, peak RSS at most 300 MB and within 1.5x between the 200 MB and the large run; the nightly fails on a 20% drop.")
	b.line("")
	if p := r.Run.Perf; p == nil || len(p.Runs) == 0 {
		b.line("r17 didn't run in this benchmark.")
	} else {
		b.line("| Input | SQL | Exit | Wall time | MB/s | Peak RSS | Passes (ms) |")
		b.line("|---|---|---|---|---|---|---|")
		for _, pr := range p.Runs {
			b.row(pr.Input, mb(pr.InputBytes), strconv.Itoa(pr.Exit), dur(pr.WallMS), fmt.Sprintf("%.1f", pr.MBps), mb(pr.MaxRSSKB*1024), phases(pr.PhasesMS))
		}
		b.line("")
		verdict := "within the limits"
		if !p.Pass {
			verdict = "outside the limits"
		}
		b.linef("Peak RSS ratio (largest over smallest): %.2f, limit %.1f. Result: %s.", p.RSSRatio, maxRSSRatio, verdict)
		for _, cmp := range p.Compared {
			b.linef("- %s: %.1f MB/s against %.1f in the baseline (%.1f%% drop, limit %.0f%%).", cmp.Input, cmp.Now, cmp.Baseline, cmp.DropPct, maxDropPct)
		}
		for _, n := range p.Notes {
			b.line("- " + n)
		}
	}
	b.line("")

	b.line("## Other tools")
	b.line("")
	if len(r.Tools) == 0 {
		b.line("No other tool ran in this benchmark.")
	} else {
		b.line("| Tool | Version | Input | Production URLs | Personal values | Live keys | Serialized integrity | Side effects | Result |")
		b.line("|---|---|---|---|---|---|---|---|---|")
		for _, t := range r.Tools {
			if t.NotRun != "" {
				b.row(t.Title, orDash(t.Version), "", NotRun, NotRun, NotRun, NotRun, NotRun, NotRun)
				continue
			}
			for _, in := range t.Inputs {
				b.row(t.Title, orDash(t.Version), in.Input, toolCell(t, MeasureURLs, in), toolCell(t, MeasureCanaries, in), toolCell(t, MeasureLiveKeys, in),
					toolCell(t, MeasureIntegrity, in), toolCell(t, MeasureSideEffects, in), in.Outcome)
			}
		}
		b.line("")
		b.line("can't see: outside what the tool does, never a miss · not run: the tool couldn't run here (the reason is below)")
		b.line("")
		for _, t := range r.Tools {
			if t.NotRun != "" {
				b.linef("- **%s** not run: %s.", t.Title, strings.TrimSuffix(t.NotRun, "."))
				continue
			}
			for _, in := range t.Inputs {
				b.linef("- **%s** on %s: %s.", t.Title, in.Input, strings.TrimSuffix(orDash(in.Detail), "."))
			}
		}
		b.line("")
		b.line("How each tool runs and its configuration: `testbed/tools/README.md`.")
	}
	b.line("")

	b.line("## What this does not show")
	b.line("")
	for _, n := range NotShown {
		b.line("- " + n)
	}
	b.line("")

	b.line("## Details")
	b.line("")
	for _, s := range r.Scored.Scenarios {
		ms := byID[s.ID]
		run := r.Run.Scenarios[s.ID]
		b.linef("**%s %s** (%s, %s, %s). %s.", s.ID, cmpOr(s.Title, ms.Title), ms.Kind, ms.Stack, dur(run.WallMS), s.Outcome)
		if s.Pending != "" {
			b.line("Pending: " + s.Pending + ".")
		}
		for _, p := range s.Partial {
			b.line("Not checked yet: " + p + ".")
		}
		for _, cs := range s.Cases {
			name := cmpOr(cs.Name, "run")
			switch {
			case cs.Pending != "":
				b.linef("- %s: pending, %s.", name, cs.Pending)
				continue
			case cs.Detail != "":
				b.linef("- %s: error, %s.", name, cs.Detail)
				continue
			}
			var parts []string
			for _, g := range cs.Gates {
				v := "held"
				if !g.Pass {
					v = "FAILED"
				}
				if d := strings.TrimSpace(g.Detail); d != "" {
					v += " (" + d + ")"
				}
				parts = append(parts, g.Name+" "+v)
			}
			b.linef("- %s: %s, exit %d. %s.", name, cs.Outcome, cs.Exit, strings.Join(parts, "; "))
		}
		b.line("")
	}

	b.line("## Run it")
	b.line("")
	b.line("Docker with Compose v2 and Go. From a clean checkout:")
	b.line("")
	b.line("```sh")
	b.line("make -C testbed up          # build and start the sealed testbed, seed the canaries (127.0.0.1:18920-18939)")
	b.line("make -C testbed seal        # prove no container reaches a public address")
	b.line("make -C testbed bench       # every scenario, the control pass and the other tools; writes docs/benchmark.md")
	b.line("make -C testbed reproduce   # run it twice and fail if the score differs")
	b.line("make -C testbed down        # remove the containers and their volumes")
	b.line("```")
	b.line("")
	b.line("`results.json` (canary IDs and counts, never a value) stays in `testbed/bench/work/`. " +
		"`go run -tags testbed ./testbed/bench -doc docs/benchmark.md -render testbed/bench/work/results.json` writes this page again from it.")
	_, err := io.WriteString(w, b.String())
	return err
}

// docWriter builds the Markdown.
type docWriter struct{ strings.Builder }

func (b *docWriter) line(s string) { _, _ = b.WriteString(s + "\n") }

func (b *docWriter) linef(format string, a ...any) { b.line(fmt.Sprintf(format, a...)) }

// row writes a table row; a | or a line break inside a cell is escaped.
func (b *docWriter) row(cells ...string) {
	for i, c := range cells {
		c = strings.ReplaceAll(c, "|", `\|`)
		cells[i] = strings.ReplaceAll(strings.ReplaceAll(c, "\r", ""), "\n", " ")
	}
	b.line("| " + strings.Join(cells, " | ") + " |")
}

// gateSummary is a scenario's gates in one cell: how many held plus the
// names of those that failed.
func gateSummary(s ScenarioResult) string {
	if s.Pending != "" {
		return "pending"
	}
	held, total := 0, 0
	var failed []string
	for _, c := range s.Cases {
		if c.Pending != "" || c.Detail != "" {
			continue
		}
		for _, g := range c.Gates {
			total++
			if g.Pass {
				held++
			} else if !slices.Contains(failed, g.Name) {
				failed = append(failed, g.Name)
			}
		}
	}
	out := fmt.Sprintf("%d of %d held", held, total)
	if len(failed) > 0 {
		out += "; failed: " + strings.Join(failed, ", ")
	}
	return out
}

// gate3Rows are the per-scenario side-effect counts from run.
func gate3Rows(r Results) [][]string {
	var rows [][]string
	for _, s := range r.Scored.Scenarios {
		run, ok := r.Run.Scenarios[s.ID]
		if !ok {
			continue
		}
		names := make([]string, 0, len(run.Cases))
		for k := range run.Cases {
			names = append(names, k)
		}
		slices.Sort(names)
		for _, k := range names {
			c := run.Cases[k]
			if c.Gate3 == nil {
				continue
			}
			id := s.ID
			if k != "-" {
				id += "/" + k
			}
			rounds, reqs := "-", "-"
			if c.Drill != nil {
				rounds = strconv.Itoa(c.Drill.Rounds)
			}
			if c.Traffic != nil {
				reqs = num(c.Traffic.Requests)
			}
			rows = append(rows, []string{id, num(c.Gate3.Sinkhole), num(c.Gate3.StubLive), num(c.Gate3.EchoRealRecips), rounds, reqs})
		}
	}
	return rows
}

// toolCell is one measure of a tool on an input.
func toolCell(t ToolResult, measure string, in ToolInput) string {
	if !slices.Contains(t.Judged, measure) {
		return "can't see"
	}
	if in.Outcome == Errored {
		return "error"
	}
	left := func(c *Count) string {
		if c == nil {
			return "-"
		}
		return fmt.Sprintf("%s of %s left", num(c.Left), num(c.Of))
	}
	switch measure {
	case MeasureURLs:
		s := left(in.URLs)
		if in.Collateral != nil && in.Collateral.Left > 0 {
			s += fmt.Sprintf("; broke %s of %s lookalikes and addresses", num(in.Collateral.Left), num(in.Collateral.Of))
		}
		return s
	case MeasureCanaries:
		return left(in.Canaries)
	case MeasureLiveKeys:
		return left(in.LiveKeys)
	case MeasureIntegrity:
		if in.Integrity == nil {
			return "-"
		}
		return fmt.Sprintf("%s of %s broken", num(in.Integrity.Left), num(in.Integrity.Of))
	case MeasureSideEffects:
		if in.SideEffects == nil {
			return "-"
		}
		return num(in.SideEffects.Left) + " got out"
	}
	return "-"
}

// kindList is "28 copy, 4 prepare, ..." in a fixed order.
func kindList(kinds map[string]int) string {
	var parts []string
	for _, k := range []string{manifest.KindCopy, manifest.KindPrepare, manifest.KindVerify, manifest.KindEnv} {
		if n := kinds[k]; n > 0 {
			parts = append(parts, fmt.Sprintf("%d %s", n, k))
		}
	}
	return strings.Join(parts, ", ")
}

// phases is "index 120, transform 900" in pass order.
func phases(p map[string]int64) string {
	var parts []string
	for _, k := range []string{"index", "transform", "import", "verify"} {
		if v, ok := p[k]; ok {
			parts = append(parts, fmt.Sprintf("%s %s", k, num(int(v))))
		}
	}
	return orDash(strings.Join(parts, ", "))
}

// num writes n with thousands separators: 1,715.
func num(n int) string {
	s := strconv.Itoa(n)
	neg := strings.HasPrefix(s, "-")
	s = strings.TrimPrefix(s, "-")
	for i := len(s) - 3; i > 0; i -= 3 {
		s = s[:i] + "," + s[i:]
	}
	if neg {
		return "-" + s
	}
	return s
}

// mb writes bytes as MB (powers of 1,000), one decimal under 10.
func mb(b int64) string {
	v := float64(b) / 1e6
	if v < 10 {
		return fmt.Sprintf("%.1f MB", v)
	}
	return num(int(v+0.5)) + " MB"
}

// dur writes milliseconds as 10m37s, 4.2s or 350ms.
func dur(ms int64) string {
	d := time.Duration(ms) * time.Millisecond
	switch {
	case d >= time.Minute:
		return d.Round(time.Second).String()
	case d >= time.Second:
		return d.Round(100 * time.Millisecond).String()
	}
	return d.String()
}

// writeDocFile writes the page to path (0644: it is published), through a
// temporary file so a failed run never leaves half a page.
func writeDocFile(path string, r Results, f *manifest.File) error {
	if err := os.MkdirAll(filepath.Dir(path), 0o750); err != nil {
		return err
	}
	tmp := path + ".tmp"
	out, err := os.OpenFile(tmp, os.O_CREATE|os.O_TRUNC|os.O_WRONLY, 0o644) // #nosec G302 G304 -- a published doc the operator names
	if err != nil {
		return err
	}
	err = WriteDoc(out, r, f)
	if cerr := out.Close(); err == nil {
		err = cerr
	}
	if err != nil {
		_ = os.Remove(tmp)
		return err
	}
	return os.Rename(tmp, path)
}
